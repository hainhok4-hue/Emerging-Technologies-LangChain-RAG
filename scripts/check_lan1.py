"""Offline-first evidence audit. Never fabricates runtime outputs.
Run from the project root: python scripts/check_lan1.py [--after-run]
"""
from pathlib import Path
from datetime import datetime
import argparse, json, csv, sys, ast
from pypdf import PdfReader

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'ket_qua'
OUT.mkdir(parents=True,exist_ok=True)
parser=argparse.ArgumentParser()
parser.add_argument('--after-run',action='store_true')
args=parser.parse_args()
results=[]
def check(label,ok,details=''):
    state='PASS' if ok else 'MISSING / NEEDS ACTION'
    results.append((label,state,details))
    print(f'[{state}] {label}  {details}')

pdfs=list((ROOT/'data/pdfs').glob('*.pdf'))
check('PDF files present',bool(pdfs),f'files={len(pdfs)}')
num_pages=0
for path in pdfs:
    try:
        reader=PdfReader(path)
        num_pages +=len(reader.pages)
        check(f'PDF readable: {path.name}',bool(reader.pages) and all(p.extract_text() for p in reader.pages),f'pages={len(reader.pages)}')
    except Exception as exc:
        check(f'PDF readable: {path.name}',False,str(exc))
modules=['app.py','config.py','src/pdf_reader.py','src/text_chunker.py','src/vector_store.py','src/qa.py','src/pipeline.py']
for filename in modules:
    try:
        ast.parse((ROOT/filename).read_text(encoding='utf-8'))
        check('Python AST: '+filename,True)
    except Exception as exc:
        check('Python AST: '+filename,False,str(exc))
nb=ROOT/'notebooks/DEMO_TUNG_HAM.ipynb'
try:
    data=json.loads(nb.read_text(encoding='utf-8'))
    check('Notebook JSON present',bool(data.get('cells')),f"cells={len(data['cells'])}")
    for i,cell in enumerate(data['cells']):
        if cell['cell_type']=='code': ast.parse(''.join(cell['source']))
    check('Notebook code syntax valid',True)
except Exception as exc:
    check('Notebook integrity',False,str(exc))
for filename in ['tai_lieu/02_LUU_DO.md','tai_lieu/LUU_DO_RAG_TONG_QUAT.png','tai_lieu/LUU_DO_KIEM_TRA_LOI.png',
                 'tai_lieu/03_INPUT_OUTPUT_VA_CODE.md','tai_lieu/04_CAU_HOI_TINH_HUONG.md','tai_lieu/15_CAU_TRAC_NGHIEM.txt',
                 'tai_lieu/05_METHOD_INPUT_OUTPUT_CODE_EN.pdf']:
    check('Required resource: '+filename,(ROOT/filename).exists())

# Runtime evidence must have actual notebook outputs and exactly five CSV rows.
executed=ROOT/'notebooks/DEMO_TUNG_HAM_DA_CHAY.ipynb'
run_ok=False
if executed.exists():
    try:
        run=json.loads(executed.read_text(encoding='utf-8'))
        count=sum(bool(c.get('outputs')) for c in run.get('cells',[]) if c.get('cell_type')=='code')
        failed=any(o.get('output_type')=='error' for c in run.get('cells',[]) for o in c.get('outputs',[]))
        run_ok=count>=10 and not failed
        check('Executed notebook with real outputs',run_ok,f'code_cells_with_outputs={count}, errors={failed}')
    except Exception as exc: check('Executed notebook with real outputs',False,str(exc))
else: check('Executed notebook with real outputs',False,'run 05_CHAY_NOTEBOOK_VA_LUU_KET_QUA.bat on Windows')
csvfile=OUT/'ket_qua_5_cau_hinh.csv'
csv_ok=False
if csvfile.exists():
    try:
        with csvfile.open(encoding='utf-8-sig',newline='') as f: rows=list(csv.DictReader(f))
        csv_ok=(len(rows)==5 and set(r['name'] for r in rows)==set('ABCDE') and all(r.get('index_seconds') not in (None,'') for r in rows))
        check('Five measured A-E configurations CSV',csv_ok,f'rows={len(rows)}')
    except Exception as exc:check('Five measured A-E configurations CSV',False,str(exc))
else:check('Five measured A-E configurations CSV',False,'created by notebook execution, not supplied in advance')
pytest_report=OUT/'pytest_ket_qua.txt'
pytest_ok=False
if pytest_report.exists():
    details=pytest_report.read_text(encoding='utf-8', errors='replace')
    import re
    pytest_ok=(re.search(r'\b3 passed\b',details) is not None
               and re.search(r'\b(FAILED|ERRORS?|failed|error)\b', details) is None)
    check('Actual pytest result: all 3 tests passed',pytest_ok,details.strip().splitlines()[-1] if details.strip() else 'empty report')
else:
    check('Actual pytest result: all 3 tests passed',False,'run 05_...bat to produce output')
report=OUT/'BAO_CAO_KIEM_TRA_LAN1.txt'
report.write_text('LANGCHAIN PDF QA — ROUND 1 EVIDENCE CHECK\nGenerated by check_lan1.py\n'+datetime.now().isoformat(timespec='seconds')+'\n\n'+
                  '\n'.join(f'{a}: {b} | {c}' for a,b,c in results)+'\n\nNOTE: PASS for source structure is not proof of successful LLM execution.\n',encoding='utf-8')
print('Audit saved to:',report)
if args.after_run and not (run_ok and csv_ok and pytest_ok):sys.exit(1)
